from docx.text.paragraph import Paragraph
from docx.table import Table


def add(el):
    sect_pr.addprevious(el)
    return el


def set_par(p_el, *texts):
    """依序把文字放進段落的前幾個 run，多的 run 刪掉，保留原格式。"""
    par = Paragraph(p_el, doc._body)
    runs = par.runs
    for i, r in enumerate(runs):
        if i < len(texts):
            r.text = texts[i]
        else:
            r._r.getparent().remove(r._r)


def fill_table(t_el, rows, n_blank=0):
    tbl = Table(t_el, doc._body)
    row_proto = copy.deepcopy(tbl.rows[1]._tr)
    alt_proto = copy.deepcopy(tbl.rows[2]._tr) if len(tbl.rows) > 2 else row_proto
    for tr in [r._tr for r in tbl.rows[1:]]:
        t_el.remove(tr)
    all_rows = list(rows) + [None] * n_blank
    for i, vals in enumerate(all_rows):
        tr = copy.deepcopy(row_proto if i % 2 == 0 else alt_proto)
        t_el.append(tr)
        cells = tbl.rows[-1].cells
        for j, cell in enumerate(cells):
            par = cell.paragraphs[0]
            for extra in cell.paragraphs[1:]:
                extra._p.getparent().remove(extra._p)
            v = "" if vals is None else vals[j]
            runs = par.runs
            if runs:
                runs[0].text = v
                for r in runs[1:]:
                    r._r.getparent().remove(r._r)
            else:
                par.add_run(v)
    return tbl


def set_header(tbl, names):
    for cell, name in zip(tbl.rows[0].cells, names):
        cell.paragraphs[0].runs[0].text = name


